#![cfg(unix)]
//! `simit projects facts` over fixture checkouts, compared with the golden
//! document fleetix consumes. Regenerate it with `SIMIT_BLESS=1`.

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

use serde_json::{Value, json};

#[allow(dead_code)]
mod common;

const MARKER: &str = "# Generated by simit. Manual edits will be reported as ci=drift.";
const PINNED: &str = "4c6841cce19327927ea8a8f6e856276dd5c878f0";
const ENGINE: &str = "8a132e416caf9cc58a753005b804343181477200";
const LOCKED: &str = "de3325be17104fbdb0d70f1da38149d4016f1790";
const HARBOR_LOCKED: &str = "432cde792b74e5fdce8ed6e71b555e535f2b83b5";

fn write(root: &Path, path: &str, content: &str) {
    let path = root.join(path);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, content).unwrap();
}

fn git(root: &Path, args: &[&str]) {
    let status = Command::new("git")
        .current_dir(root)
        .args(args)
        .env("GIT_CONFIG_GLOBAL", "/dev/null")
        .env("GIT_CONFIG_NOSYSTEM", "1")
        .status()
        .unwrap();
    assert!(status.success(), "git {args:?}");
}

/// A checkout with an origin remote and no commits.
fn checkout(root: &Path, name: &str, origin: &str) -> PathBuf {
    let path = root.join(name);
    fs::create_dir_all(&path).unwrap();
    git(&path, &["init", "--quiet"]);
    git(&path, &["remote", "add", "origin", origin]);
    path
}

fn package(root: &Path, name: &str, metadata: &str) {
    write(
        root,
        "Cargo.toml",
        &format!(
            "[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\n{metadata}\n[workspace]\n"
        ),
    );
    write(root, "src/main.rs", "fn main() {}\n");
}

/// A `nix` that records every invocation and fails.
fn nix_stub(root: &Path) -> PathBuf {
    let bin = root.join("stub-bin");
    fs::create_dir_all(&bin).unwrap();
    let nix = bin.join("nix");
    fs::write(
        &nix,
        format!(
            "#!/bin/sh\necho \"$@\" >> '{}'\necho 'stub nix refused evaluation' >&2\nexit 97\n",
            root.join("nix-invocations").display()
        ),
    )
    .unwrap();
    fs::set_permissions(&nix, fs::Permissions::from_mode(0o755)).unwrap();
    bin
}

fn facts(root: &Path, args: &[&str]) -> Output {
    let path = format!(
        "{}:{}",
        nix_stub(root).display(),
        std::env::var("PATH").unwrap_or_default()
    );
    Command::new(env!("CARGO_BIN_EXE_simit"))
        .current_dir(root)
        .args(["projects", "facts"])
        .args(args)
        .env("PATH", path)
        .env("HOME", root.join("home"))
        .env("XDG_CONFIG_HOME", root.join("home/.config"))
        .env("XDG_DATA_HOME", root.join("home/.local/share"))
        .env("GIT_CONFIG_GLOBAL", "/dev/null")
        .env("GIT_CONFIG_NOSYSTEM", "1")
        .env_remove("SIMIT_NO_REGISTRY")
        .env_remove("SIMIT_NO_FLAKE_EVAL")
        .output()
        .unwrap()
}

fn fixtures(root: &Path) {
    // A GitHub Actions repository with drifted CI and every kind of pin.
    let drifted = checkout(root, "drifted", "git@github.com:example/drifted.git");
    package(&drifted, "drifted", "");
    write(
        &drifted,
        "simit.toml",
        &format!(
            "[ci]\nplatform = \"github\"\nprovider = \"actions\"\n\n\
             [[ci.required_gates]]\nid = \"parity\"\n\
             run = \"nix run github:caniko/simit/{PINNED} -- init ci --check\"\n\n\
             [release.attic]\ncache = \"canix\"\nurl = \"https://attic.example\"\ntoken_name = \"drifted\"\n"
        ),
    );
    write(
        &drifted,
        ".github/workflows/ci.yaml",
        &format!(
            "{MARKER}\nname: CI\non:\n  push:\n    branches: [trunk]\n  pull_request:\njobs:\n  test:\n    runs-on: ubuntu-24.04\n    env:\n      \
             SIMIT_CI_ENGINE_REVISION: ${{{{ vars.SIMIT_CI_ENGINE_REVISION || '{ENGINE}' }}}}\n    \
             steps:\n      - name: parity\n        run: nix run github:caniko/simit/{PINNED} -- init ci --check\n      \
             - run: nix run --no-write-lock-file git+https://github.com/caniko/simit.git -- init flake --check\n"
        ),
    );
    write(
        &drifted,
        ".github/workflows/publish-crate.yaml",
        &format!(
            "{MARKER}\njobs:\n  publish:\n    runs-on: [self-hosted, atlas]\n    env:\n      \
             SIMIT_PUBLISHER_REVISION: ${{{{ vars.SIMIT_PUBLISHER_REVISION }}}}\n"
        ),
    );
    write(&drifted, ".github/workflows/release.yml", "name: release\n");
    write(
        &drifted,
        "README.md",
        "# drifted\n\n<!-- simit:badges:start -->\nstale\n<!-- simit:badges:end -->\n",
    );
    write(
        &drifted,
        "scripts/release.sh",
        "#!/bin/sh\n# simit is not invoked by this comment\nsimit release --dry-run\ncargo install simit\ncargo install --locked --git https://github.com/caniko/simit.git --rev 4c6841cce19327927ea8a8f6e856276dd5c878f0 simit\n",
    );
    write(
        &drifted,
        "flake.lock",
        &serde_json::to_string_pretty(&json!({
            "root": "root",
            "version": 7,
            "nodes": {
                "root": {"inputs": {"simit": "simit", "harbor": "harbor", "tool": "tool"}},
                "simit": {"locked": {"type": "github", "owner": "caniko", "repo": "simit", "rev": LOCKED}},
                "harbor": {"inputs": {"simit": "simit_2"}, "locked": {"type": "github", "owner": "caniko", "repo": "harbor", "rev": PINNED}},
                "simit_2": {"locked": {"type": "git", "url": "https://github.com/caniko/simit.git", "rev": HARBOR_LOCKED}},
                "tool": {"inputs": {"simit": []}, "locked": {"type": "github", "owner": "caniko", "repo": "tool", "rev": ENGINE}}
            }
        }))
        .unwrap(),
    );
    write(
        &drifted,
        "Cargo.lock",
        &format!(
            "version = 4\n\n[[package]]\nname = \"drifted\"\nversion = \"0.1.0\"\n\n\
             [[package]]\nname = \"simit\"\nversion = \"0.21.0\"\n\
             source = \"git+https://github.com/caniko/simit?rev={PINNED}#{PINNED}\"\n"
        ),
    );

    // Crow CI on GitHub cannot run, and codefloe Crow has no updater adapter yet.
    for (name, origin) in [
        (
            "crow-on-github",
            "https://github.com/example/crow-on-github.git",
        ),
        ("pink", "ssh://git@codefloe.com:2222/example/pink.git"),
    ] {
        let repo = checkout(root, name, origin);
        package(&repo, name, "");
        write(
            &repo,
            ".crow/ci.yaml",
            &format!(
                "{MARKER}\nwhen:\n  - event: [push, pull_request]\nlabels:\n  platform: linux/amd64\nsteps:\n  - name: test\n    image: rust\n"
            ),
        );
    }

    // A flake-declared config is never evaluated without --eval-flake.
    let flake = checkout(
        root,
        "flake-config",
        "https://github.com/example/flake-config",
    );
    write(
        &flake,
        "flake.nix",
        "{\n  outputs = _: {\n    simitConfig = { ci.platform = \"github\"; };\n  };\n}\n",
    );
    write(
        &flake,
        ".github/workflows/ci.yaml",
        &format!("{MARKER}\njobs:\n  test:\n    runs-on: ubuntu-latest\n"),
    );

    // Two config sources conflict.
    let conflict = checkout(root, "conflict", "https://github.com/example/conflict");
    package(
        &conflict,
        "conflict",
        "\n[package.metadata.simit.ci]\nplatform = \"github\"\n",
    );
    write(&conflict, "simit.toml", "[ci]\nplatform = \"github\"\n");

    // Not a forge checkout.
    fs::create_dir_all(root.join("no-origin")).unwrap();
    git(&root.join("no-origin"), &["init", "--quiet"]);
}

/// Replace values that change between runs and releases.
fn normalize(mut document: Value) -> Value {
    document["observedAt"] = json!("<observedAt>");
    document["producer"]["version"] = json!("<version>");
    for error in document["errors"].as_array_mut().unwrap() {
        error["message"] = json!("<message>");
    }
    document
}

#[test]
fn facts_match_the_golden_document_without_evaluating_flakes_or_writing() {
    let temporary = tempfile::tempdir().unwrap();
    let root = temporary.path();
    fixtures(root);
    let output = facts(
        root,
        &[
            "drifted",
            "crow-on-github",
            "pink",
            "flake-config",
            "conflict",
            "no-origin",
            "missing",
        ],
    );
    assert!(output.status.success(), "{output:?}");
    assert!(
        !root.join("nix-invocations").exists(),
        "facts evaluated a flake without --eval-flake"
    );
    assert!(
        !root.join("home/.local/share/simit").exists(),
        "facts wrote the project registry"
    );
    let document = normalize(serde_json::from_slice(&output.stdout).unwrap());
    let golden = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/supply-facts/simit-usage-facts.v1.json");
    let rendered = format!("{}\n", serde_json::to_string_pretty(&document).unwrap());
    if std::env::var_os("SIMIT_BLESS").is_some() {
        fs::write(&golden, &rendered).unwrap();
    }
    assert_eq!(
        rendered,
        fs::read_to_string(&golden).unwrap(),
        "golden facts changed; rerun with SIMIT_BLESS=1 and review the diff"
    );
}

#[test]
fn facts_report_current_generated_ci_and_evaluate_flakes_only_on_request() {
    let temporary = tempfile::tempdir().unwrap();
    let root = temporary.path();
    let current = checkout(root, "current", "https://github.com/example/current");
    package(&current, "current", "");
    let init = Command::new(env!("CARGO_BIN_EXE_simit"))
        .current_dir(&current)
        .args(["init", "ci", "--platform", "github"])
        .env("HOME", root.join("home"))
        .env("XDG_CONFIG_HOME", root.join("home/.config"))
        .env("SIMIT_NO_REGISTRY", "1")
        .output()
        .unwrap();
    assert!(init.status.success(), "{init:?}");
    let release = Command::new(env!("CARGO_BIN_EXE_simit"))
        .current_dir(&current)
        .args(["init", "release", "--platform", "github"])
        .env("SIMIT_MAINTAINERS_GPG", common::maintainer_key_path())
        .env("HOME", root.join("home"))
        .env("XDG_CONFIG_HOME", root.join("home/.config"))
        .env("SIMIT_NO_REGISTRY", "1")
        .output()
        .unwrap();
    assert!(release.status.success(), "{release:?}");
    let flake = checkout(
        root,
        "flake-config",
        "https://github.com/example/flake-config",
    );
    write(
        &flake,
        "flake.nix",
        "{ outputs = _: { simitConfig = { }; }; }\n",
    );

    let output = facts(root, &["current", "flake-config", "--eval-flake"]);
    assert!(output.status.success(), "{output:?}");
    let document: Value = serde_json::from_slice(&output.stdout).unwrap();
    let node = |id: &str| {
        document["nodes"]
            .as_array()
            .unwrap()
            .iter()
            .find(|node| node["id"] == id)
            .unwrap_or_else(|| panic!("missing {id}"))
            .clone()
    };
    assert_eq!(
        node("usage:github.com/example/current#ci.primary")["attrs"]["state"],
        "current"
    );
    assert_eq!(
        node("usage:github.com/example/current#release.workflow")["attrs"]["state"],
        "current"
    );
    assert!(
        document["errors"].as_array().unwrap().is_empty(),
        "{document:#}"
    );
    let blockers = node("repo:github.com/example/flake-config")["blockers"].clone();
    let unresolved = blockers
        .as_array()
        .unwrap()
        .iter()
        .find(|blocker| blocker["code"] == "config-unresolved")
        .unwrap();
    assert!(
        unresolved["reason"]
            .as_str()
            .unwrap()
            .contains("stub nix refused evaluation"),
        "{unresolved}"
    );
    assert!(root.join("nix-invocations").exists());

    let workflow = current.join(".github/workflows/release.yml");
    let edited = format!("{}# local edit\n", fs::read_to_string(&workflow).unwrap());
    fs::write(&workflow, edited).unwrap();
    let output = facts(root, &["current"]);
    let document: Value = serde_json::from_slice(&output.stdout).unwrap();
    let release = document["nodes"]
        .as_array()
        .unwrap()
        .iter()
        .find(|node| node["id"] == "usage:github.com/example/current#release.workflow")
        .unwrap();
    assert_eq!(release["attrs"]["state"], "drift", "{document:#}");
}
