use std::{fs, path::Path};

mod common;

fn fixture(kind: &str, policy: &str) -> tempfile::TempDir {
    let directory = tempfile::tempdir().unwrap();
    let root = directory.path();
    fs::write(root.join("flake.nix"), "{}\n").unwrap();
    match kind {
        "rust" => {
            fs::create_dir(root.join("src")).unwrap();
            fs::write(root.join("src/lib.rs"), "pub fn fixture() {}\n").unwrap();
            fs::write(root.join("Cargo.toml"), "[package]\nname = 'fixture'\nversion = '0.1.0'\nedition = '2021'\nlicense = 'MIT'\n[workspace]\n").unwrap();
        }
        "python" => {
            fs::write(
                root.join("pyproject.toml"),
                "[project]\nname = 'fixture'\nversion = '0.1.0'\nrequires-python = '>=3.12'\n",
            )
            .unwrap();
            fs::write(root.join("uv.lock"), "version = 1\n").unwrap();
        }
        "nix" => {}
        _ => panic!("unexpected fixture kind"),
    }
    fs::write(root.join("simit.toml"), policy).unwrap();
    directory
}

fn run(root: &Path, tail: &[&str]) -> std::process::Output {
    common::simit()
        .env_remove("SIMIT_MAINTAINERS_GPG")
        .env("SIMIT_NO_REGISTRY", "1")
        .current_dir(root)
        .args(["init", "ci", "--primary-only"])
        .args(tail)
        .output()
        .unwrap()
}

#[test]
fn primary_ci_scope_preserves_publication_files_and_policy_across_backends() {
    for (kind, policy, primary) in [
        (
            "rust",
            "[ci]\nplatform = 'github'\nprovider = 'actions'\nruntime = 'nix'\nrunner = 'ubuntu-24.04'\nworkspace = true\nworkspace_strategy = 'aggregate'\npublish_strategy = 'coordinated'\npublish_crates = true\n",
            ".github/workflows/ci.yaml",
        ),
        (
            "rust",
            "[ci]\nplatform = 'forgejo'\nprovider = 'crow'\nruntime = 'nix'\nrunner = 'codefloe-global'\npublish_crates = true\n",
            ".crow/build.yaml",
        ),
        (
            "python",
            "[ci]\nplatform = 'github'\nprovider = 'actions'\nruntime = 'nix'\nrunner = 'ubuntu-24.04'\nwith_pypi_publish = true\n",
            ".github/workflows/ci.yaml",
        ),
        (
            "nix",
            "[ci]\nplatform = 'github'\nprovider = 'actions'\nruntime = 'nix'\nrunner = 'ubuntu-24.04'\nnix_builds = ['.#default']\n",
            ".github/workflows/nix-builds.yaml",
        ),
    ] {
        let directory = fixture(kind, policy);
        let root = directory.path();
        let retained = [
            ".github/workflows/publish-workspace.yaml",
            ".github/workflows/trusted-publish-workspace.yaml",
            ".github/workflows/pages.yaml",
            ".github/workflows/review.yaml",
            ".crow/pages.yaml",
            ".crow/release.yaml",
        ];
        let content = "# Generated by simit. Manual edits will be reported as ci=drift.\nname: retained\non: workflow_dispatch\njobs: {}\n";
        for path in retained {
            let path = root.join(path);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, content).unwrap();
        }
        let output = run(root, &[]);
        assert!(
            output.status.success(),
            "{kind}: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        assert!(root.join(primary).is_file(), "{kind}: {primary}");
        assert_eq!(fs::read_to_string(root.join("simit.toml")).unwrap(), policy);
        assert!(
            !root.join("keys").exists(),
            "ordinary CI must not create release trust roots"
        );
        for path in retained {
            assert_eq!(
                fs::read_to_string(root.join(path)).unwrap(),
                content,
                "{kind}: {path}"
            );
        }
        let output = run(root, &["--check", "--diff"]);
        assert!(
            output.status.success(),
            "{kind}: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        fs::write(root.join(primary), "drift\n").unwrap();
        let output = run(root, &["--check", "--diff"]);
        assert!(!output.status.success(), "primary drift must still fail");
    }
}

#[test]
fn primary_ci_scope_keeps_native_prebuild_and_rejects_mixed_scope_flags() {
    let directory = fixture(
        "rust",
        "[ci]\nplatform = 'github'\nprovider = 'actions'\nruntime = 'nix'\nrunner = 'ubuntu-24.04'\nnix_builds = ['.#default']\n[prebuild]\npublish_attic = false\n[prebuild.system_runners]\nx86_64-linux = 'ubuntu-24.04'\n",
    );
    let root = directory.path();
    let output = run(root, &[]);
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(root.join(".github/workflows/prebuild.yaml").exists());
    let generated = fs::read(root.join(".github/workflows/prebuild.yaml")).unwrap();
    fs::write(
        root.join(".github/workflows/prebuild.yaml"),
        "native build drift\n",
    )
    .unwrap();
    let checked = run(root, &["--check", "--diff"]);
    assert!(!checked.status.success());
    assert!(String::from_utf8_lossy(&checked.stderr).contains("prebuild.yaml differs"));
    assert!(run(root, &[]).status.success());
    assert_eq!(
        fs::read(root.join(".github/workflows/prebuild.yaml")).unwrap(),
        generated
    );
    for flag in ["--pages-only", "--prebuild-only", "--review-only"] {
        let output = run(root, &[flag]);
        assert!(!output.status.success(), "conflicting scope {flag}");
    }
}

fn write(root: &Path, path: &str, content: &str) {
    let path = root.join(path);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, content).unwrap();
}

fn snapshot(root: &Path) -> std::collections::BTreeMap<std::path::PathBuf, Vec<u8>> {
    fn collect(
        root: &Path,
        directory: &Path,
        files: &mut std::collections::BTreeMap<std::path::PathBuf, Vec<u8>>,
    ) {
        for entry in fs::read_dir(directory).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                collect(root, &path, files);
            } else {
                files.insert(
                    path.strip_prefix(root).unwrap().to_path_buf(),
                    fs::read(path).unwrap(),
                );
            }
        }
    }
    let mut files = std::collections::BTreeMap::new();
    collect(root, root, &mut files);
    files
}

fn full(root: &Path, flags: &[&str]) -> std::process::Output {
    common::simit()
        .current_dir(root)
        .env("SIMIT_NO_REGISTRY", "1")
        .args(["init", "ci"])
        .args(flags)
        .output()
        .unwrap()
}

#[test]
fn primary_scope_never_renders_or_retires_template_owned_publishers() {
    for name in ["ci-release.yaml", "build-release.yaml"] {
        let policy = format!(
            "[ci]\nplatform = 'github'\nruntime = 'nix'\nrunner = 'ubuntu-24.04'\n[ci.workflow_templates]\n'.github/workflows/{name}' = '.simit/missing-publisher.in'\n"
        );
        let directory = fixture("rust", &policy);
        let root = directory.path();
        let publisher = format!(".github/workflows/{name}");
        let content = "# Simit workflow template: .simit/missing-publisher.in\n# Generated by simit. Manual edits will be reported as ci=drift.\nname: publisher\njobs: {}\n";
        write(root, &publisher, content);
        let output = full(root, &["--check", "--diff"]);
        assert!(!output.status.success());
        assert!(String::from_utf8_lossy(&output.stderr).contains("resolving workflow template"));
        for flags in [&[][..], &["--check", "--diff"][..]] {
            let output = run(root, flags);
            assert!(
                output.status.success(),
                "{name}: {}",
                String::from_utf8_lossy(&output.stderr)
            );
            assert_eq!(fs::read_to_string(root.join(&publisher)).unwrap(), content);
        }
        // Ownership survives removing the mapping; a primary-looking basename
        // cannot reclassify a former template output as ordinary CI.
        fs::write(
            root.join("simit.toml"),
            policy.split("[ci.workflow_templates]").next().unwrap(),
        )
        .unwrap();
        assert!(run(root, &[]).status.success());
        assert_eq!(fs::read_to_string(root.join(&publisher)).unwrap(), content);
        assert!(run(root, &["--check", "--diff"]).status.success());
        // Full generation still owns template retirement.
        let output = full(root, &[]);
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        assert!(!root.join(&publisher).exists());
    }
}

#[test]
fn printed_remediation_executes_with_the_effective_backend_and_scope() {
    for (kind, backend, primary, overrides) in [
        (
            "rust",
            "platform = 'github'\nprovider = 'actions'",
            ".github/workflows/ci.yaml",
            vec![],
        ),
        (
            "python",
            "platform = 'github'\nprovider = 'actions'",
            ".github/workflows/ci.yaml",
            vec![],
        ),
        (
            "nix",
            "platform = 'github'\nprovider = 'actions'",
            ".github/workflows/ci.yaml",
            vec![],
        ),
        (
            "nix",
            "platform = 'gitlab'\nprovider = 'actions'",
            ".gitlab-ci.yml",
            vec![],
        ),
        (
            "rust",
            "platform = 'forgejo'\nprovider = 'crow'",
            ".crow/build.jsonnet",
            vec!["--crow-format", "jsonnet"],
        ),
        (
            "python",
            "platform = 'forgejo'\nprovider = 'crow'",
            ".crow/ci.jsonnet",
            vec!["--crow-format", "jsonnet"],
        ),
        // CLI backend overrides must win over the saved project backend.
        (
            "rust",
            "platform = 'forgejo'\nprovider = 'actions'",
            ".github/workflows/ci.yaml",
            vec!["--platform", "github"],
        ),
    ] {
        let policy = format!("[ci]\n{backend}\nruntime = 'nix'\nrunner = 'ubuntu-24.04'\n");
        let directory = fixture(kind, &policy);
        let root = directory.path();
        write(root, ".github/workflows/pages.yaml", "retained pages\n");
        write(root, ".crow/publish-crate.yaml", "retained publisher\n");
        write(root, "README.md", "# Fixture\nunchanged badges\n");
        let output = run(root, &overrides);
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        let expected = fs::read(root.join(primary))
            .unwrap_or_else(|error| panic!("{kind} {backend} {primary}: {error}"));
        fs::write(root.join(primary), "drift\n").unwrap();
        let mut expected_files = snapshot(root);
        expected_files.insert(primary.into(), expected.clone());
        let mut flags = overrides.clone();
        flags.extend(["--check", "--diff"]);
        let output = run(root, &flags);
        assert!(!output.status.success());
        let stderr = String::from_utf8_lossy(&output.stderr);
        let command = stderr
            .split("run `")
            .nth(1)
            .unwrap()
            .split('`')
            .next()
            .unwrap();
        assert!(command.contains("--primary-only"), "{command}");
        let binary_dir = Path::new(env!("CARGO_BIN_EXE_simit")).parent().unwrap();
        let path = std::env::join_paths(
            std::iter::once(binary_dir.to_path_buf())
                .chain(std::env::split_paths(&std::env::var_os("PATH").unwrap())),
        )
        .unwrap();
        let output = std::process::Command::new("sh")
            .args(["-c", command])
            .current_dir(root)
            .env("PATH", path)
            .env("SIMIT_NO_REGISTRY", "1")
            .env_remove("SIMIT_MAINTAINERS_GPG")
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "{command}: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        assert_eq!(fs::read(root.join(primary)).unwrap(), expected, "{command}");
        assert_eq!(
            snapshot(root),
            expected_files,
            "{command} changed other outputs"
        );
        assert_eq!(fs::read_to_string(root.join("simit.toml")).unwrap(), policy);
        assert_eq!(
            fs::read_to_string(root.join("README.md")).unwrap(),
            "# Fixture\nunchanged badges\n"
        );
        assert_eq!(
            fs::read_to_string(root.join(".github/workflows/pages.yaml")).unwrap(),
            "retained pages\n"
        );
        assert_eq!(
            fs::read_to_string(root.join(".crow/publish-crate.yaml")).unwrap(),
            "retained publisher\n"
        );
        assert!(!root.join("keys").exists());
        assert!(run(root, &flags).status.success());
    }
}

#[test]
fn scoped_cleanup_owns_only_obsolete_builtin_primary_workflows() {
    for (backend, directory, stem) in [
        (
            "platform = 'github'\nprovider = 'actions'",
            ".github/workflows",
            "ci",
        ),
        ("platform = 'forgejo'\nprovider = 'crow'", ".crow", "build"),
    ] {
        let policy = format!(
            "[ci]\n{backend}\nruntime = 'nix'\nrunner = 'ubuntu-24.04'\nworkspace = true\npublish_crates = true\nwith_deny = true\n"
        );
        let directory_fixture = fixture("rust", &policy);
        let root = directory_fixture.path();
        fs::write(
            root.join("Cargo.toml"),
            "[workspace]\nmembers = ['release', 'utility']\nresolver = '2'\n",
        )
        .unwrap();
        for package in ["release", "utility"] {
            write(
                root,
                &format!("{package}/Cargo.toml"),
                &format!(
                    "[package]\nname = '{package}'\nversion = '0.1.0'\nedition = '2021'\nlicense = 'MIT'\n"
                ),
            );
            write(
                root,
                &format!("{package}/src/lib.rs"),
                "pub fn fixture() {}\n",
            );
        }
        let marked = "# Generated by simit. Manual edits will be reported as ci=drift.\nname: retained\njobs: {}\n";
        let preserved = [
            format!("{directory}/{stem}-hand-owned.yaml"),
            // These publisher names include the independent Cargo, Python and
            // npm component outputs introduced by PR #58.
            format!("{directory}/publish-crate-release.yaml"),
            format!("{directory}/trusted-publish-crate-release.yaml"),
            format!("{directory}/publish-python-python.yaml"),
            format!("{directory}/publish-npm-node.yaml"),
            format!("{directory}/release-artifacts-release.yaml"),
        ];
        for path in &preserved {
            write(
                root,
                path,
                if path.contains("hand-owned") {
                    "name: hand-owned\njobs: {}\n"
                } else {
                    marked
                },
            );
        }
        write(root, "keys/maintainers.gpg", "retained trust\n");
        write(root, "README.md", "retained badges\n");
        let output = run(root, &[]);
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        assert!(
            !root.join("deny.toml").exists(),
            "primary CI must not create policy"
        );
        for package in ["release", "utility"] {
            assert!(
                root.join(format!("{directory}/{stem}-{package}.yaml"))
                    .exists()
            );
        }
        let obsolete = format!("{directory}/{stem}-old.yaml");
        write(root, &obsolete, marked);
        let before = snapshot(root);
        let checked = run(root, &["--check", "--diff"]);
        assert!(!checked.status.success());
        assert!(
            String::from_utf8_lossy(&checked.stderr)
                .contains(&format!("{obsolete} is extra (obsolete)"))
        );
        assert_eq!(snapshot(root), before, "check must be read-only");
        assert!(run(root, &[]).status.success());
        let mut expected = before;
        expected.remove(Path::new(&obsolete));
        assert_eq!(snapshot(root), expected);
        assert!(run(root, &["--check", "--diff"]).status.success());
    }
}

#[test]
fn scoped_primary_matches_full_generation_with_independent_lanes_and_grouped_builds() {
    let policy = "[ci]\nplatform = 'github'\nprovider = 'actions'\nruntime = 'nix'\nrunner = 'ubuntu-24.04'\npublish_crates = true\nindependent_lanes = true\nnix_builds = ['.#default']\n[ci.nix_build]\ncapture_results = true\n[ci.nix_build.groups]\nmain = ['.#default']\n[review]\nrole = 'controller'\n";
    let directory = fixture("rust", policy);
    let root = directory.path();
    let output = full(root, &[]);
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    let before = snapshot(root);
    let ci = fs::read_to_string(root.join(".github/workflows/ci.yaml")).unwrap();
    let yaml: serde_yaml::Value = serde_yaml::from_str(&ci).unwrap();
    for lane in ["rust", "evaluation", "realization"] {
        assert!(yaml["jobs"][lane].is_mapping(), "missing #54 lane {lane}");
    }
    let builds: serde_yaml::Value = serde_yaml::from_str(
        &fs::read_to_string(root.join(".github/workflows/nix-builds.yaml")).unwrap(),
    )
    .unwrap();
    assert_eq!(
        builds["jobs"]["build"]["strategy"]["matrix"]["include"][0]["group"].as_str(),
        Some("main")
    );
    assert!(
        root.join(".github/workflows/trusted-publish-crate.yaml")
            .exists()
    );
    assert!(
        root.join(".github/workflows/review-repository.yml")
            .exists()
    );
    assert!(run(root, &["--check", "--diff"]).status.success());
    assert!(run(root, &[]).status.success());
    assert_eq!(
        snapshot(root),
        before,
        "scoped and full primary outputs differ"
    );
    assert!(full(root, &["--check", "--diff"]).status.success());
}

